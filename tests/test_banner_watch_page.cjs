const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('../website/node_modules/jsdom');
const site = 'https://fresh-moves-fix.vercel.app/';
const html = fs.readFileSync('website/public/watch/banner/index.html', 'utf8');
const d = new JSDOM(html, {url: site + 'watch/banner/'}).window.document;
const video = d.querySelector('main video');
assert.equal(d.querySelectorAll('main video').length, 1);
assert(video && video.hasAttribute('controls') && video.hasAttribute('playsinline'));
assert(!video.hasAttribute('autoplay'), 'the video starts only on user request');
assert(video.hasAttribute('data-music-ignore'), 'the silent clip should not pause site music');
assert.equal(video.src, site + 'fresh-moves-banner.mp4');
assert.equal(video.poster, site + 'fresh-moves-banner-poster.png');
assert(d.querySelector('h1').textContent.includes('Banner background animation'));
assert.match(d.querySelector('.watch-caption').textContent, /character.*separate layers/i);
assert.equal(d.querySelector('link[rel=canonical]').href, site + 'watch/banner/');
assert(fs.readFileSync('website/public/fresh-moves-banner-poster.png').equals(fs.readFileSync('website/fresh-moves-banner-poster.png')));
const home = new JSDOM(fs.readFileSync('website/public/index.html','utf8'), {url:site}).window.document;
assert.equal(home.querySelector('.banner-watch-link a').href, site + 'watch/banner/');
const sitemap = new JSDOM(fs.readFileSync('website/public/sitemap.xml','utf8'), {contentType:'text/xml'}).window.document;
const entries = [...sitemap.getElementsByTagNameNS('http://www.sitemaps.org/schemas/sitemap/0.9','url')];
const entry = entries.find(e => e.getElementsByTagNameNS('http://www.sitemaps.org/schemas/sitemap/0.9','loc')[0].textContent === site + 'watch/banner/');
assert(entry, 'watch page is in the sitemap');
const ns = 'http://www.google.com/schemas/sitemap-video/1.1';
assert.equal(entry.getElementsByTagNameNS(ns, 'thumbnail_loc')[0].textContent, video.poster);
assert.equal(entry.getElementsByTagNameNS(ns, 'content_loc')[0].textContent, video.src);
assert.equal(entry.getElementsByTagNameNS(ns, 'duration')[0].textContent, '8');
assert(entry.getElementsByTagNameNS(ns, 'title')[0].textContent);
assert(entry.getElementsByTagNameNS(ns, 'description')[0].textContent);
console.log('Watch page, controls, homepage link, media and sitemap metadata passed');
