const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('../website/node_modules/jsdom');
const html = fs.readFileSync('website/public/creations/index.html', 'utf8');
const dom = new JSDOM(html, {url:'https://example.test/creations/'});
const d = dom.window.document;
const section = d.querySelector('section.project-mods');
assert(section);
assert.match(section.textContent, /separate projects by their original creators/);
const cards = [...section.querySelectorAll('.project-card')];
assert.equal(cards.length, 3);
const card = name => cards.find(c => c.querySelector('h2').textContent === name);
assert.equal(card('Minecraft Skins').getAttribute('href'), '../minecraft-skins/');
assert.equal(card('Minecraft Skins').dataset.projectCard, 'minecraft-skins');
assert.equal(card('Glowing Eyes').getAttribute('href'), '../editor/#glowing-eyes-downloads');
assert.equal(card('Glowing Eyes').dataset.projectCard, 'editor');
assert.match(card('Glowing Eyes').textContent, /unofficial experimental builds/i);
assert.equal(card('Reactions').getAttribute('href'), '../editor/#mod-tools-title');
assert.equal(card('Reactions').dataset.projectCard, 'editor');
assert.equal(d.querySelectorAll('#projects-grid .project-card').length, 7);
assert.equal(d.getElementById('show-locked-projects').getAttribute('aria-controls'), 'projects-grid project-mods-grid');
dom.window.close();
console.log('Projects mod cards link to existing tools and preserve destination locks');
